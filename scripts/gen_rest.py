#!/usr/bin/env python3
"""Generate lightweight REST operation registries from public OpenAPI YAML.

Usage: python scripts/gen_rest.py --spec-dir /path/to/product-rest [--check]
The contract source directory can also be set with TRIPORT_SPEC_DIR.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path
from typing import Any

# pyyaml is a declared [dev] dependency (it is NOT a pydantic transitive —
# the old comment here claimed otherwise and the import failed on a clean
# `pip install -e ".[dev]"`).
import yaml

CHAINS = ("sol", "eth", "polygon", "tron", "stellar", "wallet")
PASCAL = {
    "sol": "Sol",
    "eth": "Eth",
    "polygon": "Polygon",
    "tron": "Tron",
    "stellar": "Stellar",
    "wallet": "Wallet",
}
HTTP_METHODS = ("get", "post", "put", "delete", "patch")


SPEC_DIR: Path | None = None


def spec_path(chain: str) -> Path:
    if SPEC_DIR is None:
        raise ValueError("Pass --spec-dir or set TRIPORT_SPEC_DIR")
    return SPEC_DIR / f"{chain}.yaml"


def out_dir() -> Path:
    return Path(__file__).resolve().parents[1] / "triport" / "generated" / "rest"


def render_types() -> str:
    return (
        "# AUTO-GENERATED by sdk/python/scripts/gen_rest.py — DO NOT EDIT.\n"
        "# Shared types for the per-chain REST operation registries.\n"
        "\n"
        "from __future__ import annotations\n"
        "\n"
        "from dataclasses import dataclass\n"
        "from typing import Literal, Mapping\n"
        "\n"
        "Tier = Literal['free', 'basic', 'pro', 'business', 'enterprise']\n"
        "HttpMethod = Literal['get', 'post', 'put', 'delete', 'patch']\n"
        "\n"
        "\n"
        "@dataclass(frozen=True, slots=True)\n"
        "class OperationTier:\n"
        '    """Per-operation tier metadata (REST mirror of MethodTier in generated/rpc)."""\n'
        "    required: Tier | None\n"
        "    category: str | None\n"
        "    rps: Mapping[Tier, int] | None\n"
        "    path: str\n"
        "    method: HttpMethod\n"
    )


def render(chain: str, doc: dict[str, Any]) -> str:
    pascal = PASCAL[chain]
    paths = doc.get("paths") or {}
    ops: list[dict[str, Any]] = []
    for path, methods in paths.items():
        if not isinstance(methods, dict):
            continue
        for m in HTTP_METHODS:
            op = methods.get(m)
            if isinstance(op, dict) and op.get("operationId"):
                ops.append({"name": op["operationId"], "path": path, "method": m, "op": op})

    out: list[str] = []
    out.append("# AUTO-GENERATED by sdk/python/scripts/gen_rest.py — DO NOT EDIT.")
    out.append(f"# Source: docs/api/product-rest/{chain}.yaml.")
    out.append("# Regenerate with: python scripts/gen_rest.py")
    out.append("")
    out.append("from __future__ import annotations")
    out.append("")
    out.append("from typing import Any, Final, Literal, Mapping, TypedDict")
    out.append("")
    out.append("from ._types import OperationTier")
    out.append("")
    if chain == "stellar":
        out.extend(
            [
                "class StellarHorizonQuery(TypedDict, total=False):",
                "    cursor: str",
                "    limit: int",
                "    order: Literal['asc', 'desc']",
                "    asset_code: str",
                "    asset_issuer: str",
                "",
                "",
                "class StellarHorizonPathParams(TypedDict, total=False):",
                "    ledger: str | int",
                "    account: str",
                "",
                "",
                "# Horizon HAL dictionaries are returned as-is (_links/_embedded are not renamed).",
                "StellarHALResponse = Mapping[str, Any]",
                "",
            ]
        )
    out.append(f"{pascal}OperationName = Literal[")
    for o in ops:
        out.append(f"    {json.dumps(o['name'])},")
    out.append("]")
    out.append("")
    out.append(
        f"{chain.upper()}_OPERATIONS: Final[Mapping[{pascal}OperationName, OperationTier]] = {{"
    )
    for o in ops:
        op = o["op"]
        tier = op.get("x-tier-required")
        cat = op.get("x-tier-category")
        rps = op.get("x-rate-limit-rps")
        out.append(f"    {json.dumps(o['name'])}: OperationTier(")
        out.append(f"        required={json.dumps(tier) if tier else 'None'},")
        out.append(f"        category={json.dumps(cat) if cat else 'None'},")
        if rps:
            items = ", ".join(f"{json.dumps(k)}: {v}" for k, v in rps.items())
            out.append(f"        rps={{{items}}},")
        else:
            out.append("        rps=None,")
        out.append(f"        path={json.dumps(o['path'])},")
        out.append(f"        method={json.dumps(o['method'])},")
        out.append("    ),")
    out.append("}")
    out.append("")
    return "\n".join(out)


def render_index() -> str:
    out = ["# AUTO-GENERATED by sdk/python/scripts/gen_rest.py — DO NOT EDIT.\n"]
    out.append("from ._types import HttpMethod, OperationTier, Tier")
    for c in CHAINS:
        pascal = PASCAL[c]
        if c == "stellar":
            out.append(
                "from .stellar import (STELLAR_OPERATIONS, StellarHALResponse, "
                "StellarHorizonPathParams, StellarHorizonQuery, StellarOperationName)"
            )
        else:
            out.append(f"from .{c} import {pascal}OperationName, {c.upper()}_OPERATIONS")
    out.append("")
    out.append("__all__ = [")
    out.append('    "HttpMethod",')
    out.append('    "OperationTier",')
    out.append('    "Tier",')
    for c in CHAINS:
        out.append(f'    "{PASCAL[c]}OperationName",')
        out.append(f'    "{c.upper()}_OPERATIONS",')
    out.extend(
        [
            '    "StellarHorizonPathParams",',
            '    "StellarHorizonQuery",',
            '    "StellarHALResponse",',
        ]
    )
    out.append("]")
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(prog="gen_rest.py")
    ap.add_argument("--check", action="store_true", help="diff-only; nonzero on drift")
    global SPEC_DIR
    ap.add_argument(
        "--spec-dir",
        type=Path,
        default=os.environ.get("TRIPORT_SPEC_DIR"),
        help="Directory containing the public API contracts",
    )
    args = ap.parse_args()
    if args.spec_dir is None:
        ap.error("--spec-dir or TRIPORT_SPEC_DIR is required")
    SPEC_DIR = Path(args.spec_dir)

    out_dir().mkdir(parents=True, exist_ok=True)
    rc = 0

    types_txt = render_types()
    rc |= write_or_check(out_dir() / "_types.py", types_txt, args.check)

    for chain in CHAINS:
        with open(spec_path(chain), encoding="utf-8") as f:
            doc = yaml.safe_load(f)
        rc |= write_or_check(out_dir() / f"{chain}.py", render(chain, doc), args.check)

    rc |= write_or_check(out_dir() / "__init__.py", render_index(), args.check)

    if rc == 0 and args.check:
        print("ok: gen_rest check clean")
    return rc


def write_or_check(path: Path, content: str, check: bool) -> int:
    if check:
        existing = path.read_text(encoding="utf-8") if path.exists() else ""
        if existing.strip() != content.strip():
            print(
                f"drift: {path.relative_to(Path(__file__).resolve().parents[1])}", file=sys.stderr
            )
            return 1
        return 0
    path.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {path.relative_to(Path(__file__).resolve().parents[1])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
