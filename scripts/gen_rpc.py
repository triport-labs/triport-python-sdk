#!/usr/bin/env python3
"""Generate reviewed public JSON-RPC registries and schema-derived wire types.

Usage: python scripts/gen_rpc.py --spec-dir /path/to/json-rpc [--check]
Optional method categories: --categories-file /path/to/categories.yaml.
Inputs may instead be supplied through TRIPORT_SPEC_DIR and TRIPORT_CATEGORIES_FILE.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path
from typing import Any

CHAINS = ("sol", "eth", "polygon", "tron", "bsc", "robinhood", "stellar", "ton", "base")
PASCAL = {
    "sol": "Sol",
    "eth": "Eth",
    "polygon": "Polygon",
    "tron": "Tron",
    "bsc": "Bsc",
    "robinhood": "Robinhood",
    "stellar": "Stellar",
    "ton": "Ton",
    "base": "Base",
}


SPEC_DIR: Path | None = None


def spec_path(chain: str) -> Path:
    if SPEC_DIR is None:
        raise ValueError("Pass --spec-dir or set TRIPORT_SPEC_DIR")
    return SPEC_DIR / f"{chain}.openrpc.json"


def out_dir() -> Path:
    return Path(__file__).resolve().parents[1] / "triport" / "generated" / "rpc"


def py_safe(name: str) -> str:
    """Quote method names that aren't valid Python identifiers.

    None in our specs today, but defensive against future spec additions.
    """
    if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name):
        return name
    return json.dumps(name)


CATEGORY_FILE: Path | None = None


def configured_categories(chain: str) -> dict[str, str]:
    if CATEGORY_FILE is None:
        return {}
    import yaml

    document = yaml.safe_load(CATEGORY_FILE.read_text(encoding="utf-8"))
    return dict(document.get(chain, {}))


def render(chain: str, doc: dict[str, Any]) -> str:
    pascal = PASCAL[chain]
    title = doc.get("info", {}).get("title", f"{chain} JSON-RPC")
    version = doc.get("info", {}).get("version", "0")
    manifest_path = Path(__file__).resolve().parents[1] / "tests/fixtures/methods.json"
    allowed = {m["name"] for m in json.loads(manifest_path.read_text(encoding="utf-8"))[chain]}
    methods = [m for m in doc.get("methods", []) if m["name"] in allowed]
    categories = configured_categories(chain)

    out: list[str] = []
    out.append("# AUTO-GENERATED by sdk/python/scripts/gen_rpc.py — DO NOT EDIT.")
    if chain == "robinhood":
        out.append(f"# Source: docs/api/json-rpc/{chain}.openrpc.json.")
        out.append(f"# Contract: {title} v{version}.")
    else:
        out.append(f"# Source: docs/api/json-rpc/{chain}.openrpc.json ({title} v{version}).")
    out.append("# Regenerate with: python scripts/gen_rpc.py")
    out.append("")
    out.append("from __future__ import annotations")
    out.append("")
    if chain == "base":
        out.append("import json")
        out.append("from typing import Final, Literal, Mapping")
        out.append("from urllib.parse import quote")
        out.append("")
        out.append("import httpx")
        out.append("from triport.endpoints import rpc_path")
    elif chain == "robinhood":
        out.append("from collections.abc import Mapping")
        out.append("from typing import Final, Literal")
    else:
        out.append("from typing import Final, Literal, Mapping")
    out.append("")
    out.append("from ._types import MethodTier")
    out.append("")
    out.append(f'"""{chain} JSON-RPC method registry (matrix-derived tier metadata)."""')
    out.append("")
    out.append(f"{pascal}MethodName = Literal[")
    for m in methods:
        out.append(f"    {json.dumps(m['name'])},")
    out.append("]")
    out.append("")
    out.append(f"{chain.upper()}_METHOD_TIERS: Final[Mapping[{pascal}MethodName, MethodTier]] = {{")
    for m in methods:
        name = m["name"]
        tier = m.get("x-tier-required")
        # Robinhood's card-07 runtime category registry supersedes three stale
        # heavy-method annotations in the read-only OpenRPC document.
        cat = categories.get(name, m.get("x-tier-category"))
        rps = m.get("x-rate-limit-rps")
        deprecated = bool(m.get("deprecated"))
        out.append(f"    {json.dumps(name)}: MethodTier(")
        out.append(f"        required={json.dumps(tier) if tier else 'None'},")
        out.append(f"        category={json.dumps(cat) if cat else 'None'},")
        if rps:
            # Emit rps as a dict literal in stable order.
            items = ", ".join(f"{json.dumps(k)}: {v}" for k, v in rps.items())
            out.append(f"        rps={{{items}}},")
        else:
            out.append("        rps=None,")
        out.append(f"        deprecated={deprecated},")
        out.append("    ),")
    out.append("}")
    if chain == "ton":
        out.append("")
        out.append(
            f"{chain.upper()}_PARAM_STRUCTURES: Final[Mapping[{pascal}MethodName, "
            "Literal['by-name', 'by-position', 'either']]] = {"
        )
        for m in methods:
            structure = m.get("paramStructure", "by-position")
            out.append(f"    {json.dumps(m['name'])}: {json.dumps(structure)},")
        out.append("}")
    if chain == "base":
        out.extend(
            [
                "",
                "",
                "BaseRpcProtocolErrorReason = Literal[",
                '    "invalid_envelope",',
                '    "jsonrpc_version",',
                '    "id_mismatch",',
                '    "missing_result",',
                '    "result_and_error",',
                '    "malformed_error",',
                "]",
                "",
                "",
                "class BaseRpcProtocolError(RuntimeError):",
                (
                    '    """A successful HTTP response that viol'
                    'ates the JSON-RPC 2.0 envelope contract."""'
                ),
                "",
                (
                    "    def __init__(self, reason: BaseRpcProto"
                    "colErrorReason, raw_response: str) -> None:"
                ),
                (
                    '        super().__init__(f"Base JSON-RPC protocol error '
                    '({reason}); outcome may be unknown and was not retried")'
                ),
                "        self.reason = reason",
                "        self.raw_response = raw_response",
                "",
                "",
                "def _base_response_fragment(raw_response: str, *secrets: str | None) -> str:",
                "    redacted = raw_response",
                "    for secret in secrets:",
                "        if not secret:",
                "            continue",
                '        for candidate in {secret, quote(secret, safe="")}:',
                '            redacted = redacted.replace(candidate, "[REDACTED]")',
                '    return redacted.encode("utf-8")[:512].decode("utf-8", errors="ignore")',
                "",
                "",
                "class BaseRpcError(RuntimeError):",
                "    def __init__(self, message: str, code: int | float, data: object) -> None:",
                "        super().__init__(message)",
                "        self.code = code",
                "        self.data = data",
                "",
                "",
                "class BaseRpcClient:",
                '    """Schema-registry-backed Base client; every call is exactly one POST."""',
                "",
                "    def __init__(",
                "        self,",
                "        *,",
                '        base_url: str = "https://triport.io",',
                "        api_key: str | None = None,",
                "        bearer_token: str | None = None,",
                "        transport: httpx.BaseTransport | None = None,",
                "        timeout_sec: float = 30.0,",
                "    ) -> None:",
                '        self._base_url = base_url.rstrip("/")',
                "        self._api_key = None if bearer_token else api_key",
                "        self._bearer_token = bearer_token",
                (
                    '        headers = {"Authorization": f"Bear'
                    'er {bearer_token}"} if bearer_token else {}'
                ),
                (
                    "        self._http = httpx.Client(headers=head"
                    "ers, transport=transport, timeout=timeout_sec)"
                ),
                "        self._next_id = 1",
                "",
                "    @property",
                "    def url(self) -> str:",
                '        return self._base_url + rpc_path("base", self._api_key)',
                "",
                "    def _protocol_error(",
                "        self, reason: BaseRpcProtocolErrorReason, raw_response: str",
                "    ) -> BaseRpcProtocolError:",
                "        return BaseRpcProtocolError(",
                "            reason,",
                (
                    "            _base_response_fragment(raw_re"
                    "sponse, self._api_key, self._bearer_token),"
                ),
                "        )",
                "",
                "    def call(",
                "        self, method: BaseMethodName, params: list[object] | dict[str, object]",
                "    ) -> object:",
                '        """Dispatch once. HTTP/write unknown outcomes are never auto-retried."""',
                "        request_id = self._next_id",
                "        self._next_id += 1",
                "        response = self._http.post(",
                "            self.url,",
                (
                    '            json={"jsonrpc": "2.0", "id": req'
                    'uest_id, "method": method, "params": params},'
                ),
                "        )",
                "        response.raise_for_status()",
                "        raw_response = response.text",
                "        try:",
                "            envelope = json.loads(raw_response)",
                "        except (json.JSONDecodeError, TypeError):",
                (
                    '            raise self._protocol_error("i'
                    'nvalid_envelope", raw_response) from None'
                ),
                "        if not isinstance(envelope, dict):",
                '            raise self._protocol_error("invalid_envelope", raw_response)',
                '        if envelope.get("jsonrpc") != "2.0":',
                '            raise self._protocol_error("jsonrpc_version", raw_response)',
                '        response_id = envelope.get("id")',
                (
                    "        if type(response_id) is not type("
                    "request_id) or response_id != request_id:"
                ),
                '            raise self._protocol_error("id_mismatch", raw_response)',
                '        has_result = "result" in envelope',
                '        has_error = "error" in envelope',
                "        if has_result and has_error:",
                '            raise self._protocol_error("result_and_error", raw_response)',
                "        if not has_result and not has_error:",
                '            raise self._protocol_error("missing_result", raw_response)',
                "        if has_error:",
                '            rpc_error = envelope["error"]',
                "            if (",
                "                not isinstance(rpc_error, dict)",
                '                or not isinstance(rpc_error.get("code"), (int, float))',
                '                or isinstance(rpc_error.get("code"), bool)',
                '                or not isinstance(rpc_error.get("message"), str)',
                "            ):",
                '                raise self._protocol_error("malformed_error", raw_response)',
                (
                    '            raise BaseRpcError(rpc_error["messa'
                    'ge"], rpc_error["code"], rpc_error.get("data"))'
                ),
                '        return envelope["result"]',
                "",
                "    def tier(self, method: BaseMethodName) -> MethodTier | None:",
                "        return BASE_METHOD_TIERS.get(method)",
                "",
                "    def close(self) -> None:",
                "        self._http.close()",
                "",
                "    def __enter__(self) -> BaseRpcClient:",
                "        return self",
                "",
                "    def __exit__(self, *_: object) -> None:",
                "        self.close()",
            ]
        )
    out.append("")
    return "\n".join(out)


def render_types() -> str:
    return (
        "# AUTO-GENERATED by sdk/python/scripts/gen_rpc.py — DO NOT EDIT.\n"
        "# Shared types for the per-chain method registries.\n"
        "\n"
        "from __future__ import annotations\n"
        "\n"
        "from dataclasses import dataclass\n"
        "from typing import Literal, Mapping\n"
        "\n"
        "Tier = Literal['free', 'basic', 'pro', 'business', 'enterprise']\n"
        "\n"
        "\n"
        "@dataclass(frozen=True, slots=True)\n"
        "class MethodTier:\n"
        '    """Tier annotations carried over from the OpenRPC spec."""\n'
        "    required: Tier | None\n"
        "    category: str | None\n"
        "    rps: Mapping[Tier, int] | None\n"
        "    # True when the OpenRPC spec marks this method deprecated.\n"
        "    # Callers should prefer the replacement named in the spec summary.\n"
        "    deprecated: bool = False\n"
    )


def _wire_name(prefix: str, name: str) -> str:
    return name if prefix == "Base" and name.startswith("Base") else prefix + name


def _python_literal(value: Any) -> str:
    """Render a parsed JSON value as valid Python, including nested values."""
    if value is None:
        return "None"
    if value is True:
        return "True"
    if value is False:
        return "False"
    if isinstance(value, str):
        return repr(value)
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, list):
        return "[" + ", ".join(_python_literal(item) for item in value) + "]"
    if isinstance(value, dict):
        return (
            "{"
            + ", ".join(
                f"{_python_literal(key)}: {_python_literal(item)}" for key, item in value.items()
            )
            + "}"
        )
    raise TypeError(f"unsupported JSON literal: {type(value).__name__}")


def _wire_type(schema: dict[str, Any] | None, prefix: str = "Robinhood") -> str:
    if not schema:
        return "object"
    ref = schema.get("$ref")
    if isinstance(ref, str):
        return _wire_name(prefix, ref.rsplit("/", 1)[-1])
    if "not" in schema and not schema.get("type"):
        return "NoReturn"
    values = schema.get("enum")
    if isinstance(values, list) and values:
        return "Literal[" + ", ".join(_python_literal(value) for value in values) + "]"
    # A typed object may use anyOf only to express alternative required-key
    # sets. Preserve the object's properties instead of reducing those bare
    # required clauses to object | object | object.
    alternatives = schema.get("oneOf") or (schema.get("anyOf") if not schema.get("type") else None)
    if isinstance(alternatives, list) and alternatives:
        return " | ".join(_wire_type(value, prefix) for value in alternatives)
    schema_type = schema.get("type")
    if schema_type == "string":
        return "str"
    if schema_type == "boolean":
        return "bool"
    if schema_type == "number":
        return "float"
    if schema_type == "integer":
        return "int"
    if schema_type == "null":
        return "None"
    if schema_type == "array":
        return "list[" + _wire_type(schema.get("items"), prefix) + "]"
    if schema_type == "object":
        additional = schema.get("additionalProperties")
        if isinstance(additional, dict):
            return "dict[str, " + _wire_type(additional, prefix) + "]"
        return "dict[str, object]"
    return "object"


def _schema_refs(schema: Any) -> set[str]:
    refs: set[str] = set()
    if isinstance(schema, dict):
        ref = schema.get("$ref")
        if isinstance(ref, str) and ref.startswith("#/components/schemas/"):
            refs.add(ref.rsplit("/", 1)[-1])
        for value in schema.values():
            refs.update(_schema_refs(value))
    elif isinstance(schema, list):
        for value in schema:
            refs.update(_schema_refs(value))
    return refs


def _ordered_schema_names(schemas: dict[str, Any]) -> list[str]:
    """Return dependencies before aliases so generated modules import cleanly."""
    names = {name for name in schemas if name != "TierError"}
    ordered: list[str] = []
    visiting: set[str] = set()
    visited: set[str] = set()

    def visit(name: str) -> None:
        if name in visited:
            return
        if name in visiting:
            # Recursive component: its surrounding object is emitted as a
            # dict, so retaining deterministic order is safe.
            return
        visiting.add(name)
        for dependency in sorted(_schema_refs(schemas[name]) & names):
            visit(dependency)
        visiting.remove(name)
        visited.add(name)
        ordered.append(name)

    for name in sorted(names):
        visit(name)
    return ordered


def render_wire(chain: str, doc: dict[str, Any]) -> str:
    prefix = "Base" if chain == "base" else "Robinhood"
    out = [
        "# AUTO-GENERATED by sdk/python/scripts/gen_rpc.py — DO NOT EDIT.",
        f"# Source: docs/api/json-rpc/{chain}.openrpc.json.",
        "",
        "from __future__ import annotations",
        "",
        "from typing import Literal, NoReturn, TypedDict"
        if chain == "base"
        else "from typing import Literal, TypedDict",
        "",
    ]
    schemas = doc.get("components", {}).get("schemas", {})
    for name in _ordered_schema_names(schemas):
        out.append(f"{_wire_name(prefix, name)} = {_wire_type(schemas[name], prefix)}")
    out.extend(["", f"{prefix}Params = TypedDict('{prefix}Params', {{  # noqa: UP013"])
    for method in doc.get("methods", []):
        params = method.get("params", [])
        required = sum(1 for param in params if param.get("required", True))
        variants: list[str] = []
        for count in range(required, len(params) + 1):
            parts = [_wire_type(param.get("schema"), prefix) for param in params[:count]]
            if not parts:
                variants.append("tuple[()]")
            elif len(parts) == 1:
                variants.append(f"tuple[{parts[0]},]")
            else:
                variants.append("tuple[" + ", ".join(parts) + "]")
        out.append(f"    {method['name']!r}: {' | '.join(variants)},")
    out.extend(["})", "", f"{prefix}Results = TypedDict('{prefix}Results', {{  # noqa: UP013"])
    for method in doc.get("methods", []):
        out.append(
            f"    {method['name']!r}: {_wire_type(method.get('result', {}).get('schema'), prefix)},"
        )
    out.extend(["})", ""])
    return "\n".join(out)


def render_index() -> str:
    out = ["# AUTO-GENERATED by sdk/python/scripts/gen_rpc.py — DO NOT EDIT.\n"]
    out.append("from ._types import MethodTier, Tier")
    for c in CHAINS:
        pascal = PASCAL[c]
        suffix = (
            f", {c.upper()}_PARAM_STRUCTURES"
            if c == "ton"
            else ", BaseRpcClient"
            if c == "base"
            else ""
        )
        out.append(f"from .{c} import {pascal}MethodName, {c.upper()}_METHOD_TIERS{suffix}")
    out.append("")
    # __all__ is emitted line-by-line below; there is no intermediate list.
    out.append("__all__ = [")
    out.append('    "MethodTier",')
    out.append('    "Tier",')
    for c in CHAINS:
        out.append(f'    "{PASCAL[c]}MethodName",')
        out.append(f'    "{c.upper()}_METHOD_TIERS",')
        if c == "ton":
            out.append(f'    "{c.upper()}_PARAM_STRUCTURES",')
        if c == "base":
            out.append('    "BaseRpcClient",')
    out.append("]")
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(prog="gen_rpc.py")
    ap.add_argument("--check", action="store_true", help="diff-only; nonzero exit on drift")
    ap.add_argument(
        "--chain",
        choices=CHAINS,
        help="generate/check only one chain plus its wire file and barrel",
    )
    global SPEC_DIR
    ap.add_argument(
        "--spec-dir",
        type=Path,
        default=os.environ.get("TRIPORT_SPEC_DIR"),
        help="Directory containing the public API contracts",
    )
    global CATEGORY_FILE
    ap.add_argument(
        "--categories-file",
        type=Path,
        default=os.environ.get("TRIPORT_CATEGORIES_FILE"),
        help="Optional method category overrides (YAML)",
    )
    args = ap.parse_args()
    if args.spec_dir is None:
        ap.error("--spec-dir or TRIPORT_SPEC_DIR is required")
    SPEC_DIR = Path(args.spec_dir)
    CATEGORY_FILE = args.categories_file

    rc = 0
    out_dir().mkdir(parents=True, exist_ok=True)

    # _types.py
    types_path = out_dir() / "_types.py"
    types_txt = render_types()
    if args.chain is None:
        rc |= write_or_check(types_path, types_txt, args.check)

    # Per-chain files
    active_chains = (args.chain,) if args.chain else CHAINS
    for chain in active_chains:
        with open(spec_path(chain), encoding="utf-8") as f:
            doc = json.load(f)
        txt = render(chain, doc)
        path = out_dir() / f"{chain}.py"
        rc |= write_or_check(path, txt, args.check)

    for wire_chain in ("robinhood", "base"):
        if args.chain is not None and args.chain != wire_chain:
            continue
        with open(spec_path(wire_chain), encoding="utf-8") as f:
            wire_doc = json.load(f)
        rc |= write_or_check(
            out_dir() / f"{wire_chain}_wire.py",
            render_wire(wire_chain, wire_doc),
            args.check,
        )

    # __init__.py barrel
    idx_path = out_dir() / "__init__.py"
    idx_txt = render_index()
    rc |= write_or_check(idx_path, idx_txt, args.check)

    if rc == 0 and args.check:
        print("ok: gen_rpc check clean")
    return rc


def write_or_check(path: Path, content: str, check: bool) -> int:
    if check:
        existing = path.read_text(encoding="utf-8") if path.exists() else ""
        if existing.strip() != content.strip():
            print(
                f"drift: {path.relative_to(Path(__file__).resolve().parents[1])}", file=sys.stderr
            )
            return 1
        return 0
    path.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {path.relative_to(Path(__file__).resolve().parents[1])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
